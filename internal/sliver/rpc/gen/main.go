// Command gen parses the sliver module's rpcpb.SliverRPCClient interface and
// emits capture_decorator.go: one recording pass-through method per RPC that
// drives revils' capture.Recorder.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

type rpcMethod struct {
	name       string
	paramType  string // "" for client-streaming methods (no request argument)
	resultType string // includes package qualifier; streaming types unstarred
	streaming  bool
}

func main() {
	out := flag.String("out", "capture_decorator.go", "output file")
	flag.Parse()
	methods, err := interfaceMethods()
	if err != nil {
		log.Fatal(err)
	}
	src, err := render(methods)
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("wrote %s (%d methods)", *out, len(methods))
}

func interfaceMethods() ([]rpcMethod, error) {
	dir, err := sliverModuleDir()
	if err != nil {
		return nil, err
	}
	path := filepath.Join(dir, "protobuf", "rpcpb", "services_grpc.pb.go")
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, path, nil, 0)
	if err != nil {
		return nil, err
	}
	for _, decl := range file.Decls {
		gen, ok := decl.(*ast.GenDecl)
		if !ok {
			continue
		}
		for _, spec := range gen.Specs {
			ts, ok := spec.(*ast.TypeSpec)
			if !ok || ts.Name.Name != "SliverRPCClient" {
				continue
			}
			iface, ok := ts.Type.(*ast.InterfaceType)
			if !ok {
				return nil, fmt.Errorf("SliverRPCClient is not an interface")
			}
			return collectMethods(fset, iface)
		}
	}
	return nil, fmt.Errorf("SliverRPCClient interface not found in %s", path)
}

func sliverModuleDir() (string, error) {
	cmd := exec.Command("go", "list", "-m", "-f", "{{.Dir}}", "github.com/bishopfox/sliver")
	out, err := cmd.Output()
	if err != nil {
		return "", fmt.Errorf("locate sliver module: %w", err)
	}
	dir := strings.TrimSpace(string(out))
	if dir == "" {
		return "", fmt.Errorf("sliver module dir empty")
	}
	return dir, nil
}

func collectMethods(fset *token.FileSet, iface *ast.InterfaceType) ([]rpcMethod, error) {
	var methods []rpcMethod
	for _, field := range iface.Methods.List {
		fn, ok := field.Type.(*ast.FuncType)
		if !ok || len(field.Names) == 0 {
			continue
		}
		m := rpcMethod{name: field.Names[0].Name}
		params := fn.Params.List
		results := fn.Results.List
		if len(params) == 3 {
			m.paramType = deref(fset, params[1].Type)
		}
		if len(results) != 2 {
			return nil, fmt.Errorf("%s: expected 2 results", m.name)
		}
		m.resultType, m.streaming = resultType(fset, results[0].Type)
		methods = append(methods, m)
	}
	return methods, nil
}

func deref(fset *token.FileSet, expr ast.Expr) string {
	if star, ok := expr.(*ast.StarExpr); ok {
		return renderExpr(fset, star.X)
	}
	return renderExpr(fset, expr)
}

func resultType(fset *token.FileSet, expr ast.Expr) (string, bool) {
	var typ string
	var streaming bool
	if star, ok := expr.(*ast.StarExpr); ok {
		typ = renderExpr(fset, star.X)
	} else {
		typ = renderExpr(fset, expr)
		streaming = true
	}
	if !strings.Contains(typ, ".") {
		typ = "rpcpb." + typ
	}
	return typ, streaming
}

func renderExpr(fset *token.FileSet, expr ast.Expr) string {
	var buf bytes.Buffer
	_ = printer.Fprint(&buf, fset, expr)
	return buf.String()
}

func render(methods []rpcMethod) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by internal/sliver/rpc/gen. DO NOT EDIT.\n\n")
	buf.WriteString("package rpc\n\nimport (\n\t\"context\"\n\n")
	buf.WriteString("\t\"github.com/bishopfox/sliver/protobuf/clientpb\"\n")
	buf.WriteString("\t\"github.com/bishopfox/sliver/protobuf/commonpb\"\n")
	buf.WriteString("\t\"github.com/bishopfox/sliver/protobuf/rpcpb\"\n")
	buf.WriteString("\t\"github.com/bishopfox/sliver/protobuf/sliverpb\"\n")
	buf.WriteString("\t\"github.com/gubarz/revils/capture\"\n")
	buf.WriteString("\t\"github.com/gubarz/revils/store\"\n")
	buf.WriteString("\t\"google.golang.org/grpc\"\n")
	buf.WriteString("\t\"google.golang.org/protobuf/proto\"\n")
	buf.WriteString(")\n\n")
	buf.WriteString("type captureDecorator struct {\n\tinner rpcpb.SliverRPCClient\n\trec   *capture.Recorder\n}\n\n")
	buf.WriteString("func WrapCapture(inner rpcpb.SliverRPCClient, rec *capture.Recorder) rpcpb.SliverRPCClient {\n")
	buf.WriteString("\treturn &captureDecorator{inner: inner, rec: rec}\n}\n\n")
	buf.WriteString("func endCallOnContextDone(call *capture.Call, ctx context.Context) {\n")
	buf.WriteString("\tif call == nil {\n\t\treturn\n\t}\n")
	buf.WriteString("\tgo func() {\n\t\t<-ctx.Done()\n\t\tcall.End(ctx.Err())\n\t}()\n}\n\n")
	buf.WriteString("func (d *captureDecorator) preview(ctx context.Context, method, direction string, msg proto.Message) string {\n")
	buf.WriteString("\tif msg == nil {\n\t\treturn \"\"\n\t}\n")
	buf.WriteString("\tpayload, err := proto.Marshal(msg)\n")
	buf.WriteString("\tif err != nil {\n\t\treturn \"\"\n\t}\n")
	buf.WriteString("\tann := d.rec.Annotate(ctx, method, direction, payload)\n")
	buf.WriteString("\tif direction == \"response\" {\n\t\treturn ann.ResponsePreview\n\t}\n")
	buf.WriteString("\treturn ann.RequestPreview\n}\n\n")
	for _, m := range methods {
		writeMethod(&buf, m)
	}
	return format.Source(buf.Bytes())
}

func writeMethod(buf *bytes.Buffer, m rpcMethod) {
	fullMethod := "/rpcpb.SliverRPC/" + m.name
	if m.streaming {
		fmt.Fprintf(buf, "func (d *captureDecorator) %s(ctx context.Context", m.name)
		if m.paramType != "" {
			fmt.Fprintf(buf, ", in *%s", m.paramType)
		}
		fmt.Fprintf(buf, ", opts ...grpc.CallOption) (%s, error) {\n", m.resultType)
		if m.paramType != "" {
			buf.WriteString("\tpayload, _ := proto.Marshal(in)\n")
			fmt.Fprintf(buf, "\tcall := d.rec.Begin(ctx, %q, payload)\n", fullMethod)
		} else {
			fmt.Fprintf(buf, "\tcall := d.rec.Begin(ctx, %q, nil)\n", fullMethod)
		}
		fmt.Fprintf(buf, "\tstream, err := d.inner.%s(ctx", m.name)
		if m.paramType != "" {
			buf.WriteString(", in")
		}
		buf.WriteString(", opts...)\n")
		buf.WriteString("\tif err != nil {\n\t\tcall.End(err)\n\t\treturn nil, err\n\t}\n")
		buf.WriteString("\tendCallOnContextDone(call, ctx)\n\treturn stream, nil\n}\n\n")
		return
	}
	fmt.Fprintf(buf, "func (d *captureDecorator) %s(ctx context.Context, in *%s, opts ...grpc.CallOption) (*%s, error) {\n",
		m.name, m.paramType, m.resultType)
	buf.WriteString("\tpayload, _ := proto.Marshal(in)\n")
	fmt.Fprintf(buf, "\tcall := d.rec.Begin(ctx, %q, payload)\n", fullMethod)
	buf.WriteString("\tif call == nil {\n")
	fmt.Fprintf(buf, "\t\treturn d.inner.%s(ctx, in, opts...)\n", m.name)
	buf.WriteString("\t}\n")
	fmt.Fprintf(buf, "\tcall.Message(store.DirectionRequest, payload, d.preview(ctx, %q, \"request\", in))\n", fullMethod)
	fmt.Fprintf(buf, "\tresp, err := d.inner.%s(ctx, in, opts...)\n", m.name)
	buf.WriteString("\tif err != nil {\n\t\tcall.End(err)\n\t\treturn resp, err\n\t}\n")
	buf.WriteString("\trespPayload, _ := proto.Marshal(resp)\n")
	fmt.Fprintf(buf, "\tcall.Message(store.DirectionResponse, respPayload, d.preview(ctx, %q, \"response\", resp))\n", fullMethod)
	buf.WriteString("\tcall.End(nil)\n\treturn resp, nil\n}\n\n")
}
